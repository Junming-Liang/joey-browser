#!/usr/bin/env python3
"""Generate pinned voice identities and optionally reviewed bilingual captions."""
import argparse
import hashlib
import json
import re
import struct
from pathlib import Path

from poc_data import archive_index

VOICE_SHA = 'b23a7158d19f99d0a1a7013a2fbc291ad019768a166ce93cd15d90bca04dcc72'


def normalized_pcm(raw):
    result = bytearray(len(raw))
    for offset in range(0, len(raw), 2):
        sample = struct.unpack_from('<h', raw, offset)[0]
        struct.pack_into('<h', result, offset, max(-32768, min(32767, ((sample + 4) // 8) * 8)))
    return result


def fingerprint(raw):
    value = 14695981039346656037
    for byte in raw:
        value = ((value ^ byte) * 1099511628211) & 0xffffffffffffffff
    return value


def generate(archive, transcripts):
    raw = archive.read_bytes()
    if hashlib.sha256(raw).hexdigest() != VOICE_SHA:
        raise ValueError('Voice.dat is not the pinned original archive')
    voices = []
    for entry in archive_index(raw, len(raw)):
        match = re.fullmatch(r'joey\\english\\internal\\joey_(\d+)\.wav', entry['name'], re.I)
        if not match:
            continue
        wave = raw[entry['offset']:entry['offset'] + entry['size']]
        if wave[:4] != b'RIFF' or wave[8:12] != b'WAVE':
            raise ValueError('Invalid character WAV')
        position, fmt, pcm = 12, None, None
        while position + 8 <= len(wave):
            kind, size = struct.unpack_from('<4sI', wave, position)
            position += 8
            if position + size > len(wave):
                raise ValueError('Truncated character WAV')
            if kind == b'fmt ':
                fmt = struct.unpack_from('<HHIIHH', wave, position)
            elif kind == b'data':
                if pcm is not None:
                    raise ValueError('Multiple character PCM chunks')
                pcm = wave[position:position + size]
            position += size + (size & 1)
        if fmt != (1, 1, 22050, 44100, 2, 16) or not pcm or len(pcm) % 2:
            raise ValueError('Unexpected character PCM format')
        normalized = normalized_pcm(pcm)
        if normalized_pcm(normalized) != normalized:
            raise ValueError('Original/light normalization is not idempotent')
        voices.append(dict(voiceId=int(match[1]), file=entry['name'].split('\\')[-1].lower(),
                           pcmBytes=len(pcm), sourceSHA256=hashlib.sha256(wave).hexdigest(),
                           durationFrames=len(pcm) // 2, sampleRate=22050,
                           fingerprint=fingerprint(normalized)))
    voices.sort(key=lambda row: row['voiceId'])
    if [row['voiceId'] for row in voices] != [*range(1, 73), 74]:
        raise ValueError('Unexpected character voice coverage')
    if len({row['pcmBytes'] for row in voices}) != len(voices):
        raise ValueError('Character PCM lengths must be unique')
    reviewed = {}
    if transcripts:
        for row in json.loads(transcripts.read_text()):
            voice = next((v for v in voices if v['voiceId'] == row.get('voiceId')), None)
            if (not voice or row['voiceId'] in reviewed or row.get('reviewed') is not True or
                    row.get('sourceSHA256') != voice['sourceSHA256'] or
                    any(not isinstance(row.get(lang), str) or not row[lang].strip() or
                        len(row[lang]) > 800 for lang in ('en', 'zh'))):
                raise ValueError('Caption must be unique, reviewed, bilingual, and match its source WAV')
            reviewed[row['voiceId']] = row
    catalog = {}
    for voice in voices:
        row = {key: value for key, value in voice.items() if key != 'fingerprint'}
        text = reviewed.get(voice['voiceId'])
        row.update(en=text['en'].strip() if text else '', zh=text['zh'].strip() if text else '',
                   verified=text is not None)
        catalog[voice['voiceId']] = row
    javascript = ('// Generated by prepare_subtitles.py; empty captions are deliberately not displayed.\n'
                  'export const SUBTITLE_CATALOG = Object.freeze(' +
                  json.dumps(catalog, ensure_ascii=False, indent=2) + ');\n')
    signatures = '\n'.join(f'    ({row["pcmBytes"]}, 0x{row["fingerprint"]:016x}, {row["voiceId"]}),' for row in voices)
    rust = '''// Generated by games/joey/reverse/prepare_subtitles.py from pinned original Voice.dat.
// Normalize to the existing light PCM profile so both resource qualities identify alike.
const VOICES: &[(usize, u64, u16)] = &[
''' + signatures + '''
];

pub fn candidate(channels: u32, bits: u32, size: u32) -> bool {
    channels == 1 && bits == 16 && VOICES.iter().any(|entry| entry.0 == size as usize)
}

pub fn identify(pcm: &[u8]) -> Option<u16> {
    let &(_, expected, voice) = VOICES.iter().find(|entry| entry.0 == pcm.len())?;
    let mut hash = 14695981039346656037u64;
    for bytes in pcm.chunks_exact(2) {
        let sample = i16::from_le_bytes([bytes[0], bytes[1]]) as i32;
        let normalized = (((sample + 4).div_euclid(8) * 8).clamp(-32768, 32767) as i16).to_le_bytes();
        for byte in normalized {
            hash = (hash ^ byte as u64).wrapping_mul(1099511628211);
        }
    }
    (hash == expected).then_some(voice)
}
'''
    return javascript, rust, len(reviewed)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--voice-dat', type=Path, required=True)
    parser.add_argument('--catalog-output', type=Path, required=True)
    parser.add_argument('--rust-output', type=Path, required=True)
    parser.add_argument('--transcripts', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    catalog, rust, reviewed = generate(args.voice_dat, args.transcripts)
    for path, content in [(args.catalog_output, catalog), (args.rust_output, rust)]:
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Generated file differs: {path}')
        else:
            path.write_text(content)
    print(json.dumps({'voiceIdentities': 73, 'reviewedBilingualCaptions': reviewed,
                      'originalAndLightMatch': True, 'checked': args.check}))
